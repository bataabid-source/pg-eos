const COMMISSION_SCHEMA = 'hr'; // REPLACE-ON-COPY: the module schema.
const COMMISSION_DAILY_TABLE_NAME = 'commission_daily'; // REPLACE-ON-COPY: the aggregate table.
const COMMISSION_DAILY_TABLE = `${COMMISSION_SCHEMA}.${COMMISSION_DAILY_TABLE_NAME}`;
const COMMISSION_RULES_TABLE = `${COMMISSION_SCHEMA}.commission_rules`;
const EMPLOYEES_TABLE = `${COMMISSION_SCHEMA}.employees`; // hr.employees — round-1 finding 1's own read.
const AUDIT_ACTOR_TYPE_USER = 'user'; // every actor is ctx.userId — never 'system' here.

// database/schema/13-Schema-Additions.sql:349 `applies_to text not null default 'driver'` — this
// slice reads driver rules only (brief default 1).
const COMMISSION_RULES_APPLIES_TO_DRIVER = 'driver';

// live-verified constraint name (`select conname from pg_constraint where
// conrelid='hr.commission_daily'::regclass`), never a guessed Postgres auto-generated name — same
// discipline as assign-driver-id's own repository.ts.
const UNIQUE_VIOLATION_SQLSTATE = '23505';
const COMMISSION_DAILY_UNIQUE_CONSTRAINT = 'commission_daily_work_date_employee_id_key';

// imile.shipments.internal_status allowed values (.claude/briefs/imile.brief.md §3 /
// 13B-Schema-Reference-Consolidation.sql:2375-2376 chk_shipments_internal_status) — the three this
// use case counts.
const SHIPMENT_STATUS_DELIVERED = 'delivered';
const SHIPMENT_STATUS_FAILED = 'failed';
const SHIPMENT_STATUS_RETURNED = 'returned';

// part 2 round-2 finding 1 (timezone): doc 40 §A3 / 01-Data-Model.sql:8 — the platform's business
// timezone is Asia/Kuwait. All timestamps in this table are stored UTC (`timestamptz`), so a
// `workDate` calendar-day boundary must be pinned to Asia/Kuwait EXPLICITLY, never to whatever
// TimeZone the connecting session happens to carry (same mechanism as
// modules/wms/domain/take-occupancy-snapshot/invariants.ts's own `businessDateOf` — Asia/Kuwait
// carries a fixed UTC+3 offset year-round, no DST — here expressed as a literal SQL `AT TIME ZONE`
// cast instead of a domain-level Date shift, since this is a SQL comparison against timestamptz
// columns, not a Date already in hand). `timestamptz AT TIME ZONE zone` yields the local wall-clock
// `timestamp` in that zone (used to derive a calendar date); `date::timestamp AT TIME ZONE zone`
// does the reverse — interprets a naive midnight as Kuwait-local and yields the UTC instant.
const BUSINESS_TIMEZONE = 'Asia/Kuwait';

